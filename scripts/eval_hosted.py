"""Evaluate a Prime-Inference-hosted model on the octave taskset.

No GPU: generation runs against Prime Inference, scoring runs locally against
the pinned Octave rootfs. That makes a calibration pass cost cents instead of
a pod-hour, which is the right shape for "how does this model do" questions.

Two sampling cells per level, because today's baseline work established that
they answer different questions:

- **greedy** (T=0) is comparable with the 2026-08-08 Qwen numbers in
  ``artifacts/baseline-eval-20260808/``.
- **T=1.0** is the number that matters for the WS3 G1 band, because GRPO's
  advantage comes from reward spread *within a sampled group*, so the band has
  to be measured at the rollout temperature. Choosing a curriculum mix from the
  greedy figure was already shown to be misleading.

Model choice matters: prefer the explicit ``-BF16`` repo over the cheaper
lowercase alias. WS3 §2g flags the alias as almost certainly a quantized
serving build, and quantization noise lands directly in a routing measurand.

**This is the eval client, not the train client.** ``scripts/run_baseline_eval.py``
uses ``[client] type = "train"`` against a pod-local vLLM, which tokenizes
client-side and therefore exposes ``[client.renderer] enable_thinking``. A
hosted provider has no such endpoint, so we use the default eval client, which
relays chat requests and lets the *server* apply the chat template. Thinking is
suppressed with a sampling knob instead (see ``REASONING_EFFORT`` below). The
two paths reach the same place by different routes; note it when comparing
these numbers with the Qwen baseline.

Usage:
    uv run python scripts/eval_hosted.py --plan
    uv run python scripts/eval_hosted.py --levels 1 2 3 --num-tasks 32
"""

from __future__ import annotations

import argparse
import json
import os
import shlex
import subprocess
import sys
import time
from pathlib import Path

DEFAULT_MODEL = "nvidia/NVIDIA-Nemotron-3-Nano-30B-A3B-BF16"
HELD_OUT_SEED = 20260808
MAX_TOKENS = 1536

# A per-variant sweep wants every rollout landing on a family that HAS variants.
# Left unrestricted, a 24-variant sweep over the ten-family stream spends most of
# its budget on families that still contribute one prompt per level, and the
# per-variant cells come back too thin to tell 0.00 from 0.20.
#
# `--families converted` resolves this from `generators.VARIANT_MODULES` at run
# time rather than from a list written here, so it cannot go stale as the
# conversion proceeds.
CONVERTED = "converted"

# Measured against the BF16 deployment on 2026-08-08, 17*23 with max_tokens=200:
#
#   (none)                                 60 completion tokens, 152 chars reasoning
#   reasoning_effort = "low"               60 completion tokens, 152 chars reasoning
#   reasoning_effort = "none"               4 completion tokens,   0 chars reasoning
#   chat_template_kwargs.enable_thinking    4 completion tokens,   0 chars reasoning
#
# So "none" and the chat-template kwarg are equivalent and both work; "low" is a
# no-op. We use reasoning_effort because it is a typed field on SamplingConfig
# rather than a passthrough extra, and because scripts/classify_failures.py
# already uses that idiom. Nemotron defaults thinking **on**, unlike Qwen, so
# omitting this silently spends the whole budget on reasoning_content.
REASONING_EFFORT = "none"

TEMPLATE = """# Generated by scripts/eval_hosted.py -- do not hand-edit.
model = "{model}"
num_tasks = {num_tasks}
num_rollouts = {rollouts}
max_concurrent = {concurrency}
push = false
rich = false
max_turns = 1
output_dir = "{output_dir}"
max_total_tokens = 4096

[taskset]
id = "octave-rl"
level = {level}
num_tasks = {pool_size}
seed = {seed}{families}
# Single-turn, no guide: measure the policy, not the scaffold. Scoring runs on
# this host against the pinned Octave rootfs, so no Prime Sandbox is involved.
task = {{ octave_runtime = "local", user = {{ octave_runtime = "local", max_attempts = 1, guide_enabled = false }} }}

[harness]
id = "null"

[harness.runtime]
type = "subprocess"

[client]
# Default type is "eval" -- a relay to a hosted provider. Do NOT add
# [client.renderer] here: renderer/pool_size/renderer_model_name exist only on
# the *train* client (client-side tokenization against a vLLM engine), and the
# config validator rejects them as extra inputs. base_url is a str, not a list.
base_url = "https://api.pinference.ai/api/v1"
api_key_var = "PRIME_API_KEY"

[sampling]
temperature = {temperature}
max_tokens = {max_tokens}
reasoning_effort = "{reasoning_effort}"

[timeout]
rollout = 600
finalize = 300
scoring = 60
"""


def render(path: Path, **kwargs) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(TEMPLATE.format(**kwargs))
    return path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("--reasoning-effort", default=REASONING_EFFORT)
    parser.add_argument("--output", type=Path, default=Path("outputs/hosted-eval"))
    parser.add_argument("--levels", type=int, nargs="+", default=[1, 2, 3])
    parser.add_argument("--num-tasks", type=int, default=32)
    parser.add_argument("--pool-size", type=int, default=500)
    parser.add_argument("--seed", type=int, default=HELD_OUT_SEED)
    parser.add_argument("--concurrency", type=int, default=4)
    parser.add_argument(
        "--max-tokens",
        type=int,
        default=MAX_TOKENS,
        help=(
            "Completion cap. Raise it when measuring prompt legibility: a "
            "rollout that hits the cap is a structural zero, not a capability "
            "result, and the 0.5.0 pool truncated 21%% of reshape_permute "
            "attempts at 1536. Report the truncation share with any score."
        ),
    )
    parser.add_argument(
        "--families",
        nargs="+",
        default=None,
        help=(
            "Restrict the pool to these families, or the literal 'converted' to "
            "resolve the ones currently on the variant form. Omit for all ten. "
            "Restricting changes which tasks are drawn but not the tasks "
            "themselves -- build_tasks filters the full stream -- so a "
            "restricted run stays comparable with an unrestricted one."
        ),
    )
    parser.add_argument(
        "--num-rollouts",
        type=int,
        default=1,
        help=(
            "Rollouts per task. >1 with --cells sampled measures within-group "
            "reward spread directly, which is what decides whether a group "
            "carries any GRPO advantage. Pointless with greedy (T=0 is "
            "deterministic, so every rollout in the group is identical)."
        ),
    )
    parser.add_argument(
        "--cells",
        nargs="+",
        default=["greedy", "sampled"],
        choices=["greedy", "sampled"],
    )
    parser.add_argument("--plan", action="store_true")
    parser.add_argument(
        "--validate",
        action="store_true",
        help="Append --dry-run: resolve and validate each config, run nothing.",
    )
    parser.add_argument(
        "--runner",
        default=None,
        help=(
            "Command that runs one eval config, config path appended. Defaults "
            "to the local .venv's `eval` when present, else `uv run eval @`. "
            "The venv path is preferred because `uv run` re-syncs, and a sync "
            "prunes the editable octave_rl install (PIPELINE_LOG 2026-08-08)."
        ),
    )
    args = parser.parse_args()

    families = args.families
    if families == [CONVERTED]:
        sys.path.insert(0, str(Path("environments/octave_rl").resolve()))
        from generators import VARIANT_MODULES

        families = sorted(VARIANT_MODULES)
        if not families:
            raise SystemExit("no families are on the variant form yet")
    families_line = (
        "\nfamilies = [" + ", ".join(f'"{name}"' for name in families) + "]"
        if families
        else ""
    )

    # Greedy stays at one rollout however --num-rollouts is set: T=0 is
    # deterministic, so a group of 8 would be 8 copies of one answer.
    cells = {"greedy": (0.0, 1), "sampled": (1.0, args.num_rollouts)}
    slug = args.model.rsplit("/", 1)[-1].lower()
    suffix = f"-g{args.num_rollouts}" if args.num_rollouts > 1 else ""

    jobs = []
    for cell in args.cells:
        temperature, rollouts = cells[cell]
        for level in args.levels:
            name = f"{slug}-{cell}{suffix if cell == 'sampled' else ''}-l{level}"
            config = render(
                args.output / "configs" / f"{name}.toml",
                model=args.model,
                num_tasks=args.num_tasks,
                rollouts=rollouts,
                concurrency=args.concurrency,
                level=level,
                pool_size=args.pool_size,
                seed=args.seed,
                temperature=temperature,
                families=families_line,
                max_tokens=args.max_tokens,
                reasoning_effort=args.reasoning_effort,
                output_dir=str(args.output / name),
            )
            jobs.append({"name": name, "cell": cell, "level": level,
                         "config": str(config)})

    (args.output / "plan.json").write_text(json.dumps(jobs, indent=2) + "\n")
    print(f"model     : {args.model}")
    print(f"families  : {', '.join(families) if families else 'all ten'}")
    print(f"thinking  : off (reasoning_effort={args.reasoning_effort!r})")
    print(f"max tokens: {args.max_tokens}")
    print(f"cells     : {', '.join(args.cells)}")
    total = sum(args.num_tasks * (args.num_rollouts if j["cell"] == "sampled" else 1) for j in jobs)
    print(f"rollouts  : {total}")
    for job in jobs:
        print(f"  {job['name']}")
    if args.plan:
        print("\n--plan given; nothing executed")
        return 0

    if args.runner:
        runner = shlex.split(args.runner)
    else:
        venv_eval = Path(".venv/bin/eval")
        runner = [str(venv_eval), "@"] if venv_eval.exists() else ["uv", "run", "eval", "@"]

    env = dict(os.environ)
    env.setdefault("OCTAVE_RL_OCTAVE_ROOTFS", "/opt/octave-rootfs")
    if "PRIME_API_KEY" not in env:
        raise SystemExit("PRIME_API_KEY is not set; refusing to run against a hosted API")

    failures = 0
    for job in jobs:
        print(f"\n=== {job['name']} ===", flush=True)
        started = time.monotonic()
        command = [*runner, job["config"]]
        if args.validate:
            command.append("--dry-run")
        result = subprocess.run(command, env=env, check=False)
        elapsed = time.monotonic() - started
        print(f"[{job['name']}] rc={result.returncode} in {elapsed:.0f}s", flush=True)
        failures += result.returncode != 0
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
