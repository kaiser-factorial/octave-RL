"""Render and run the fixed-scorer baseline evaluations on a pod.

Produces one eval config per (policy, level), serves each policy once, and runs
its levels against that server. Everything scores through the local Octave
runtime, so no Prime Sandbox is involved.

Deliberate deviations from the historical eval configs, all so the numbers mean
one thing rather than several:

- **Single turn.** ``max_attempts = 1``, no guide model. The historical 0.905
  came from a three-attempt interaction with a 35B guide, which measures the
  scaffold as much as the policy. Single-turn is also what WS3 specifies.
- **Fresh seed.** Disjoint from the training pool (314159) and from every
  previously used held-out seed (271828, 272828, 272829).
- **No guide model.** Removes a Prime Inference dependency and its per-token
  cost from a run that is supposed to have none.

Usage:
    uv run python scripts/run_baseline_eval.py --plan          # print, run nothing
    uv run python scripts/run_baseline_eval.py --concurrency 2
"""

from __future__ import annotations

import argparse
import json
import os
import shlex
import subprocess
import time
from pathlib import Path

HELD_OUT_SEED = 20260808
DEFAULT_LEVELS = (1, 2, 3)
# Matches the tested envelope; 2048 was measured as slower without helping.
MAX_TOKENS = 1536

EVAL_TEMPLATE = """# Generated by scripts/run_baseline_eval.py -- do not hand-edit.
model = "{model}"
num_tasks = {num_tasks}
num_rollouts = 1
max_concurrent = {concurrency}
push = false
rich = false
max_turns = 1
output_dir = "{output_dir}"
max_total_tokens = 4096

[taskset]
id = "octave-rl"
level = {level}
num_tasks = {pool_size}
seed = {seed}
# Score on this host against the pinned Octave rootfs, not in a Prime Sandbox.
task = {{ octave_runtime = "local", user = {{ octave_runtime = "local", max_attempts = 1, guide_enabled = false }} }}

[harness]
id = "null"

[harness.runtime]
type = "subprocess"

[client]
type = "train"
base_url = "http://localhost:8000/v1"
renderer_model_name = "{model}"
pool_size = {concurrency}

[client.renderer]
name = "qwen3.5"
enable_thinking = false

[sampling]
temperature = 0.0
max_tokens = {max_tokens}

[timeout]
rollout = 600
finalize = 300
scoring = 60
"""

INFERENCE_TEMPLATE = """# Generated by scripts/run_baseline_eval.py -- do not hand-edit.
enable_lora = false
gpu_memory_utilization = 0.85
api_server_count = 1
seed = 0
enable_fp32_lm_head = true
enable_fp32_router_logits = true

[server]
port = 8000
liveness_timeout_seconds = 30.0

[model]
name = "{model}"
trust_remote_code = false
dtype = "auto"
max_model_len = 4096
# RTX 6000 Ada (SM89): vLLM's CUDA-graph and bundled FlashAttention-2 paths
# both fault on Qwen3.5. These two settings are the validated workaround.
enforce_eager = true
tool_call_parser = "None"
reasoning_parser = "None"

[model.vlm]
vision_encoder_attr = "model.visual"
language_model_attr = "model.language_model"
freeze_vision_encoder = true

[parallel]
tp = 1
dp = 1

[log]
level = "info"
vf_level = "info"
json_logging = false

[vllm_extra]
attention_backend = "TRITON_ATTN"
"""


def render(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, default=Path("/workspace"))
    parser.add_argument("--prime-rl", type=Path, default=Path("/workspace/prime-rl"))
    parser.add_argument("--num-tasks", type=int, default=32)
    parser.add_argument("--pool-size", type=int, default=500)
    parser.add_argument("--concurrency", type=int, default=1)
    parser.add_argument("--levels", type=int, nargs="+", default=list(DEFAULT_LEVELS))
    parser.add_argument("--seed", type=int, default=HELD_OUT_SEED)
    parser.add_argument(
        "--policy",
        action="append",
        metavar="NAME=PATH",
        help="repeatable; defaults to base and step20 under --workspace",
    )
    parser.add_argument("--plan", action="store_true", help="render configs only")
    args = parser.parse_args()

    policies = (
        [tuple(p.split("=", 1)) for p in args.policy]
        if args.policy
        else [
            ("base", str(args.workspace / "qwen3.5-4b-base")),
            ("step20", str(args.workspace / "step20-merged")),
        ]
    )
    outputs = args.workspace / "baseline-eval"
    configs = outputs / "configs"

    plan: list[dict] = []
    for name, model in policies:
        inference_config = render(
            configs / f"inference-{name}.toml",
            INFERENCE_TEMPLATE.format(model=model),
        )
        for level in args.levels:
            eval_config = render(
                configs / f"eval-{name}-l{level}.toml",
                EVAL_TEMPLATE.format(
                    model=model,
                    num_tasks=args.num_tasks,
                    pool_size=args.pool_size,
                    concurrency=args.concurrency,
                    level=level,
                    seed=args.seed,
                    max_tokens=MAX_TOKENS,
                    output_dir=str(outputs / f"{name}-l{level}"),
                ),
            )
            plan.append(
                {
                    "policy": name,
                    "model": model,
                    "level": level,
                    "inference_config": str(inference_config),
                    "eval_config": str(eval_config),
                }
            )

    (outputs / "plan.json").write_text(json.dumps(plan, indent=2) + "\n")
    print(f"rendered {len(plan)} evaluations across {len(policies)} policies")
    for entry in plan:
        print(f"  {entry['policy']:<8} level {entry['level']}  -> {entry['eval_config']}")
    print(f"\nplan: {outputs / 'plan.json'}")

    if args.plan:
        print("\n--plan given; nothing executed")
        return 0

    env = dict(os.environ)
    env.setdefault("OCTAVE_RL_OCTAVE_ROOTFS", "/opt/octave-rootfs")
    for name, _model in policies:
        server = None
        try:
            server_log = (outputs / f"inference-{name}.log").open("w")
            server = subprocess.Popen(
                ["uv", "run", "inference", "@", str(configs / f"inference-{name}.toml")],
                cwd=args.prime_rl,
                env=env,
                stdout=server_log,
                stderr=subprocess.STDOUT,
            )
            print(f"\n[{name}] inference server pid {server.pid}; waiting for liveness")
            deadline = time.monotonic() + 900
            while time.monotonic() < deadline:
                if server.poll() is not None:
                    raise RuntimeError(f"inference server exited: {server.returncode}")
                probe = subprocess.run(
                    ["curl", "-sf", "http://localhost:8000/v1/models"],
                    capture_output=True,
                    check=False,
                )
                if probe.returncode == 0:
                    print(f"[{name}] server live")
                    break
                time.sleep(10)
            else:
                raise TimeoutError(f"[{name}] server never became live")

            for level in args.levels:
                config = configs / f"eval-{name}-l{level}.toml"
                print(f"[{name}] level {level}: {shlex.join(['uv', 'run', 'eval', '@', str(config)])}",
                      flush=True)
                started = time.monotonic()
                result = subprocess.run(
                    ["uv", "run", "eval", "@", str(config)],
                    cwd=args.prime_rl,
                    env=env,
                    check=False,
                )
                print(f"[{name}] level {level} finished rc={result.returncode} "
                      f"in {time.monotonic() - started:.0f}s", flush=True)
        finally:
            if server is not None and server.poll() is None:
                server.terminate()
                try:
                    server.wait(timeout=60)
                except subprocess.TimeoutExpired:
                    server.kill()
                print(f"[{name}] inference server stopped")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
